export function SocialIcon({ platform = '', className = 'h-5 w-5', ...props }) {
  const p = platform.toLowerCase();
  if (p.includes('github')) return <GithubIcon className={className} {...props} />;
  if (p.includes('linkedin')) return <LinkedinIcon className={className} {...props} />;
  if (p.includes('twitter') || p === 'x') return <TwitterIcon className={className} {...props} />;
  if (p.includes('youtube')) return <YoutubeIcon className={className} {...props} />;
  if (p.includes('whatsapp')) return <WhatsappIcon className={className} {...props} />;
  return <span className={`font-mono text-xs uppercase font-bold ${className}`}>{platform.substring(0, 2)}</span>;
}


